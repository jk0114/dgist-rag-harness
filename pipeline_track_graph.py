def _norm(name: str) -> str:
    return re.sub(r"\s+", "", name.strip())


def _strip_paren(name: str) -> str:
    return re.sub(r"[\(（][^)）]*[\)）]\s*$", "", name).strip()


# 과목명(정규화) -> 소속 트랙 집합. 괄호 포함/제거 두 형태 모두 키로 넣어 매칭률을 높인다.
_NAME_TO_TRACKS: dict[str, set[str]] = {}
for _track, _names in TRACK_COURSES.items():
    for _name in _names:
        for _key in (_norm(_name), _norm(_strip_paren(_name))):
            _NAME_TO_TRACKS.setdefault(_key, set()).add(_track)

# crawl_syllabus.py가 만든 PDF 파일명 패턴: {SHYY}{SHTM_DCD}_{과목번호}_{분반}_{과목명}.pdf
_SOURCE_RE = re.compile(r"^\d{4}CMN17\.\d{2}_[^_]+_\d+_(?P<name>.+)\.pdf$", re.I)


def course_tracks(source_filename: str) -> set[str]:
    """강의계획서 PDF 파일명에서 과목명을 뽑아 소속 트랙 집합을 돌려준다. 매뉴얼 등 매칭 안 되면 빈 집합."""
    m = _SOURCE_RE.match(source_filename or "")
    if not m:
        return set()
    name = m.group("name")
    for key in (_norm(name), _norm(_strip_paren(name))):
        if key in _NAME_TO_TRACKS:
            return _NAME_TO_TRACKS[key]
    return set()


def _connected(h: dict, o: dict) -> bool:
    """두 청크 사이에 edge가 있는지. ① 같은 과목(PDF)이면 트랙 여부와 무관하게 무조건 연결
    (논문의 "구조적 인접" 역할 — 같은 과목의 다른 페이지끼리는 항상 서로 근거가 되어줘야 함),
    ② 다른 과목이면 트랙을 하나라도 공유할 때만 연결 (논문의 "키워드 공유" 역할)."""
    if h["source"] == o["source"]:
        return True
    return bool(h["_tracks"] and (h["_tracks"] & o["_tracks"]))


def graph_rescore(query: str, pool_k: int = POOL_K) -> list[dict]:
    """dense top-(pool_k)로 넓게 후보를 모은 뒤, 같은 트랙/같은 과목끼리 점수를 전파해 재정렬한다.
    자르지 않고 전부 돌려준다 (실험실 페이지에서 최종 top-k 밖인 것들의 graph_score도 보려고 분리해둠).
    실제 검색은 graph_retrieve()를 쓴다."""
    pool = retrieve(query, pool_k)
    for h in pool:
        h["_tracks"] = course_tracks(h["source"])

    for h in pool:
        neighbor_scores = [o["score"] for o in pool if o is not h and _connected(h, o)]
        boost = max(neighbor_scores) if neighbor_scores else h["score"]
        h["graph_score"] = ALPHA * h["score"] + (1 - ALPHA) * boost

    pool.sort(key=lambda h: h["graph_score"], reverse=True)
    return pool


def graph_retrieve(query: str, k: int) -> list[dict]:
    return graph_rescore(query, max(POOL_K, k))[:k]


@register("track_graph", "트랙 그래프 검색: 같은 트랙 과목끼리 유사도를 전파(GNN-Ret 방식, 학습 없음) "
                          "→ '관심분야 추천' 같은 질문에서 vanilla보다 넓게 후보를 모음. 프롬프트는 vanilla와 동일.")
def track_graph(question, history, params):
    k = int(params.get("top_k", C.TOP_K))
    hits = graph_retrieve(question, k)
    msgs = [{"role": "system", "content": SYSTEM_RAG}, *history,
            {"role": "user", "content": f"[근거]\n{_ctx(hits)}\n\n[질문]\n{question}{RULE_TAIL}"}]
    return {"answer": chat(msgs), "retrieved": hits, "prompt": msgs}
